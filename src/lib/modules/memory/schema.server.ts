import { apiKey, tag } from '$lib/server/db/schema';
import { sql } from 'drizzle-orm';
import {
	type AnyPgColumn,
	boolean,
	customType,
	index,
	integer,
	jsonb,
	pgTable,
	primaryKey,
	text,
	timestamp,
	unique,
	uuid
} from 'drizzle-orm/pg-core';
import type { NoteContent } from '../notes/content';
import type { MemoryActorType } from './types';

// Mirror of migrations/0022_memory_init.sql. The SQL file is the source of truth.

function timestamptz(name: string) {
	return timestamp(name, { withTimezone: true });
}

const tsvector = customType<{ data: string }>({ dataType: () => 'tsvector' });

export const memoryCategory = pgTable(
	'memory_category',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		parentId: uuid('parent_id').references((): AnyPgColumn => memoryCategory.id, {
			onDelete: 'restrict'
		}),
		name: text('name').notNull(),
		createdAt: timestamptz('created_at').defaultNow().notNull(),
		updatedAt: timestamptz('updated_at').defaultNow().notNull()
	},
	(table) => [index('memory_category_parent_id_idx').on(table.parentId)]
);

export const memory = pgTable(
	'memory',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		title: text('title').notNull(),
		content: jsonb('content').$type<NoteContent>().notNull(),
		contentText: text('content_text').notNull().default(''),
		categoryId: uuid('category_id').references(() => memoryCategory.id, {
			onDelete: 'set null'
		}),
		pinned: boolean('pinned').notNull().default(false),
		version: integer('version').notNull().default(1),
		deletedAt: timestamptz('deleted_at'),
		createdAt: timestamptz('created_at').defaultNow().notNull(),
		updatedAt: timestamptz('updated_at').defaultNow().notNull(),
		// Generated by the database from the title and the text; never written.
		searchVector: tsvector('search_vector').generatedAlwaysAs(
			sql`setweight(to_tsvector('simple', title), 'A') || setweight(to_tsvector('simple', left(content_text, 200000)), 'B')`
		)
	},
	(table) => [
		index('memory_updated_at_idx').on(table.updatedAt.desc()),
		index('memory_deleted_at_idx').on(table.deletedAt),
		index('memory_category_id_idx').on(table.categoryId)
	]
);

export const memoryRevision = pgTable(
	'memory_revision',
	{
		id: uuid('id').primaryKey().defaultRandom(),
		memoryId: uuid('memory_id')
			.notNull()
			.references(() => memory.id, { onDelete: 'cascade' }),
		version: integer('version').notNull(),
		title: text('title').notNull(),
		content: jsonb('content').$type<NoteContent>().notNull(),
		actorType: text('actor_type').$type<MemoryActorType>().notNull(),
		actorId: text('actor_id'),
		createdAt: timestamptz('created_at').defaultNow().notNull(),
		updatedAt: timestamptz('updated_at').defaultNow().notNull()
	},
	(table) => [unique('memory_revision_memory_version_unique').on(table.memoryId, table.version)]
);

export const memoryTag = pgTable(
	'memory_tag',
	{
		memoryId: uuid('memory_id')
			.notNull()
			.references(() => memory.id, { onDelete: 'cascade' }),
		tagId: uuid('tag_id')
			.notNull()
			.references(() => tag.id, { onDelete: 'cascade' })
	},
	(table) => [
		primaryKey({ columns: [table.memoryId, table.tagId] }),
		index('memory_tag_tag_id_idx').on(table.tagId)
	]
);

export const memoryKeyCategory = pgTable(
	'memory_key_category',
	{
		apiKeyId: uuid('api_key_id')
			.notNull()
			.references(() => apiKey.id, { onDelete: 'cascade' }),
		categoryId: uuid('category_id')
			.notNull()
			.references(() => memoryCategory.id, { onDelete: 'restrict' })
	},
	(table) => [
		primaryKey({ columns: [table.apiKeyId, table.categoryId] }),
		index('memory_key_category_category_id_idx').on(table.categoryId)
	]
);
